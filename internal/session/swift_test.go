package session

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"testing"
)

var updateSwift = flag.Bool("update-swift", false, "rewrite testdata/wire/Wire.generated.swift from the Go constants")

// swiftWirePath is the native client's copy of the protocol constants. The
// handset repo's make fixtures copies it into LoupeClient.
const swiftWirePath = "../../testdata/wire/Wire.generated.swift"

// wireBytes lists the single-byte protocol constants every generated client
// copy carries, so the Swift and Kotlin files cannot list different ones.
func wireBytes() []struct {
	name string
	v    byte
} {
	return []struct {
		name string
		v    byte
	}{
		{"msgInit", MsgInit},
		{"msgFrame", MsgFrame},
		{"msgStats", MsgStats},
		{"msgPong", MsgPong},
		{"msgError", MsgError},
		{"msgEvent", MsgEvent},
		{"msgClipboard", MsgClipboard},
		{"msgControl", MsgControl},
		{"msgRotate", MsgRotate},
		{"msgEnded", MsgEnded},
		{"msgCursor", MsgCursor},
		{"msgOverlay", MsgOverlay},
		{"msgTouch", MsgTouch},
		{"msgKey", MsgKey},
		{"msgScroll", MsgScroll},
		{"msgPing", MsgPing},
		{"msgClientStats", MsgClientStats},
		{"msgHello", MsgHello},
		{"msgText", MsgText},
		{"msgTakeOver", MsgTakeOver},
		{"flagKey", flagKey},
		{"flagConfig", flagConfig},
	}
}

// swiftWire renders the protocol constants as Swift. The native viewer
// hardcodes every one of these bytes, so a renumbering here that the Swift
// file does not follow would misroute messages in silence: an init read as a
// frame is trap 9's shape on the other client.
func swiftWire() []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by internal/session/swift_test.go. DO NOT EDIT.")
	fmt.Fprintln(&b, "// Regenerate with: go test ./internal/session -run TestSwiftWireMatchesGo -update-swift")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "/// The session protocol's constants, from internal/session/protocol.go.")
	fmt.Fprintln(&b, "public enum Wire {")
	for _, c := range wireBytes() {
		fmt.Fprintf(&b, "    public static let %s: UInt8 = 0x%02X\n", c.name, c.v)
	}
	fmt.Fprintf(&b, "    public static let frameHeaderLen = %d\n", FrameHeaderLen)
	fmt.Fprintf(&b, "    public static let maxTextLen = %d\n", MaxTextLen)
	fmt.Fprintf(&b, "    public static let protocolVersion = %d\n", ProtocolVersion)
	fmt.Fprintf(&b, "    public static let minProtocolVersion = %d\n", MinProtocolVersion)
	fmt.Fprintf(&b, "    public static let endedUnsupportedProtocol = %q\n", EndedUnsupportedProtocol)
	fmt.Fprintf(&b, "    public static let quicALPN = %q\n", QUICALPN)
	fmt.Fprintln(&b, "}")
	return b.Bytes()
}

func TestSwiftWireMatchesGo(t *testing.T) {
	want := swiftWire()
	if *updateSwift {
		if err := os.WriteFile(filepath.FromSlash(swiftWirePath), want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(filepath.FromSlash(swiftWirePath))
	if err != nil {
		t.Fatalf("read %s: %v", swiftWirePath, err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is out of date with protocol.go; rerun with -update-swift.\n got:\n%s\nwant:\n%s", swiftWirePath, got, want)
	}
}
