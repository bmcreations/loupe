var updateKotlin = flag.Bool("update-kotlin", false, "rewrite testdata/wire/Wire.generated.kt from the Go constants")

// kotlinWirePath is Handset's copy of the protocol constants. The handset
// repo's make fixtures copies it into mobile/core.
const kotlinWirePath = "../../testdata/wire/Wire.generated.kt"

// kotlinWire renders the protocol constants as Kotlin, from the same table as
// swiftWire. Every message id is below 0x80, so a Byte literal needs no
// toByte().
func kotlinWire() []byte {
	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by internal/session/kotlin_test.go. DO NOT EDIT.")
	fmt.Fprintln(&b, "// Regenerate with: go test ./internal/session -run TestKotlinWireMatchesGo -update-kotlin")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package dev.bmcreations.loupe.handset.core.wire")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "/** The session protocol's constants, from internal/session/protocol.go. */")
	fmt.Fprintln(&b, "object Wire {")
	for _, c := range wireBytes() {
		fmt.Fprintf(&b, "    const val %s: Byte = 0x%02X\n", c.name, c.v)
	}
	fmt.Fprintf(&b, "    const val frameHeaderLen: Int = %d\n", FrameHeaderLen)
	fmt.Fprintf(&b, "    const val maxTextLen: Int = %d\n", MaxTextLen)
	fmt.Fprintf(&b, "    const val protocolVersion: Int = %d\n", ProtocolVersion)
	fmt.Fprintf(&b, "    const val minProtocolVersion: Int = %d\n", MinProtocolVersion)
	fmt.Fprintf(&b, "    const val endedUnsupportedProtocol: String = %q\n", EndedUnsupportedProtocol)
	fmt.Fprintf(&b, "    const val quicALPN: String = %q\n", QUICALPN)
	fmt.Fprintln(&b, "}")
	return b.Bytes()
}

func TestKotlinWireMatchesGo(t *testing.T) {
	want := kotlinWire()
	if *updateKotlin {
		if err := os.WriteFile(filepath.FromSlash(kotlinWirePath), want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(filepath.FromSlash(kotlinWirePath))
	if err != nil {
		t.Fatalf("read %s: %v", kotlinWirePath, err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s is out of date with protocol.go; rerun with -update-kotlin.\n got:\n%s\nwant:\n%s", kotlinWirePath, got, want)
	}
}

// notForClients lists the exported Msg* and flag* byte constants that no
// generated client file carries, each with why.
var notForClients = map[string]string{}

// TestWireBytesCoverProtocol keeps wireBytes in step with protocol.go: a new
// Msg* or flag* constant that is neither listed there nor excused above would
// reach clients as an unknown message in silence. Every listed value also has
// to be below 0x80, which the generated Kotlin Byte literals rely on.
func TestWireBytesCoverProtocol(t *testing.T) {
	f, err := parser.ParseFile(token.NewFileSet(), "protocol.go", nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	listed := map[string]bool{}
	for _, c := range wireBytes() {
		listed[c.name] = true
		if c.v >= 0x80 {
			t.Errorf("wireBytes %s = 0x%02X: a Kotlin Byte literal needs a value below 0x80", c.name, c.v)
		}
	}
	seen := 0
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		// Match on the name alone: an untyped or implicitly typed constant
		// (MsgFoo = 0x0D, or a bare name inheriting the line above) is still a
		// wire byte.
		for _, sp := range gd.Specs {
			vs := sp.(*ast.ValueSpec)
			for _, n := range vs.Names {
				name := n.Name
				if !strings.HasPrefix(name, "Msg") && !strings.HasPrefix(name, "flag") {
					continue
				}
				seen++
				key := strings.ToLower(name[:1]) + name[1:]
				if listed[key] {
					continue
				}
				if _, excused := notForClients[name]; !excused {
					t.Errorf("protocol.go constant %s is not in wireBytes() or notForClients", name)
				}
			}
		}
	}
	if seen == 0 {
		t.Fatal("found no Msg* or flag* constants in protocol.go; the parse is not seeing the file")
	}
	for name, why := range notForClients {
		if strings.TrimSpace(why) == "" {
			t.Errorf("notForClients[%s] needs a reason", name)
		}
	}
}
